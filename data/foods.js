/**
 * Helper to search foods by name or tag
 *
 * @param {string} query - Search term
 * @param {string} [category='all'] - Filter by category
 * @returns {Array} Filtered foods
 */
export function searchFoods(query = '', category = 'all') {
  const cleanQ = String(query).toLowerCase().trim();
  return FOODS.filter((food) => {
    const matchesCategory = category === 'all' || food.category === category;
    const matchesQuery = !cleanQ || food.name.toLowerCase().includes(cleanQ);
    return matchesCategory && matchesQuery;
  });
}

/**
 * Retrieves all foods belonging to a specific category
 *
 * @param {string} categoryId
 * @returns {Array}
 */
export function getFoodsByCategory(categoryId) {
  if (!categoryId || categoryId === 'all') return FOODS;
  return FOODS.filter((f) => f.category === categoryId);
}

/**
 * Scales nutritional values for a customized portion in grams
 *
 * @param {Object} food - Food object
 * @param {number} customGrams - New portion in grams
 * @returns {Object} Recalculated nutritional values
 */
export function scaleFoodPortion(food, customGrams) {
  const baseWeight = food.servingWeightGrams || 100;
  const factor = baseWeight > 0 ? customGrams / baseWeight : 1;

  return {
    ...food,
    servingSize: `${customGrams}g`,
    servingWeightGrams: customGrams,
    calories: Math.round(food.calories * factor),
    protein: Math.round(food.protein * factor * 10) / 10,
    carbs: Math.round(food.carbs * factor * 10) / 10,
    fat: Math.round(food.fat * factor * 10) / 10,
  };
}
